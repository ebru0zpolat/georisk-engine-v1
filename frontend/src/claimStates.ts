/**
 * Claim-state vocabulary — the single source of truth for the chip system.
 *
 * Every number rendered from engine output carries exactly one claim state. The
 * glyph, label and tooltip text live here so that tooltips, evidence bundles and
 * CSV exports all speak the same language. Colours live in App.css, keyed by
 * `[data-claim-state]`, so the palette stays with the rest of the tokens.
 */

export type ClaimState =
  | "VERIFIED"
  | "LIVE"
  | "FIXTURE"
  | "MODELLED"
  | "DERIVED"
  | "SYNTHETIC"
  | "DEGRADED"
  | "STALE"
  | "NOT_ELIGIBLE";

export type ClaimStateSpec = {
  /** Glyph shown before the label. Never rendered without the label. */
  icon: string;
  /** The code as it appears in the chip. Carries a version where one applies. */
  label: string;
  /** One-line gloss used in the claim-control list. */
  short: string;
  /** Full sentence used as the chip's tooltip, and in exported bundles. */
  tooltip: string;
};

