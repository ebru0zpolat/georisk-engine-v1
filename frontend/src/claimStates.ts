/** Display order for the claim-control section. */
export const CLAIM_STATE_ORDER: ClaimState[] = [
  "VERIFIED",
  "LIVE",
  "FIXTURE",
  "MODELLED",
  "DERIVED",
  "SYNTHETIC",
  "DEGRADED",
  "STALE",
  "NOT_ELIGIBLE",
];

export function isClaimState(value: unknown): value is ClaimState {
  return typeof value === "string" && value in CLAIM_STATES;
}

/**
 * Claim state per demo component, used when the API response does not carry
 * `component_claims`. The engine is the authority; this only keeps the fixture
 * demo honest about what each component actually is.
 */
const FALLBACK_COMPONENT_CLAIMS: Record<string, ClaimState> = {
  industrial: "MODELLED",
  pollution: "FIXTURE",
  land: "VERIFIED",
  ocean: "MODELLED",
  agriculture: "STALE",
  sensitivity: "MODELLED",
};

/**
 * Resolve the claim state for one component score. Prefers the state the engine
 * reported; falls back to the pinned demo mapping, then to MODELLED — never to
 * a stronger claim than the caller can support.
 */
export function componentClaimState(
  name: string,
  reported?: Record<string, string> | null,
): ClaimState {
  const fromEngine = reported?.[name];
  if (isClaimState(fromEngine)) return fromEngine;
  return FALLBACK_COMPONENT_CLAIMS[name] ?? "MODELLED";
}
